export function useI18n(initialLang?: SupportedLanguage) {
  const [lang, setLangState] = React.useState<SupportedLanguage>(() => {
    return initialLang || getSavedLanguage();
  });

  React.useEffect(() => {
    const handler = (e: Event) => {
      const custom = e as CustomEvent<SupportedLanguage>;
      if (custom.detail) setLangState(custom.detail);
    };
    window.addEventListener("study-buddy-lang-change", handler);
    return () => window.removeEventListener("study-buddy-lang-change", handler);
  }, []);

  const changeLanguage = React.useCallback((newLang: SupportedLanguage) => {
    setSavedLanguage(newLang);
    setLangState(newLang);
  }, []);

  const t = React.useCallback(
    (key: string): string => {
      return TRANSLATIONS[lang]?.[key] || TRANSLATIONS.en?.[key] || key;
    },
    [lang]
  );

  return { lang, setLang: changeLanguage, t };
}
