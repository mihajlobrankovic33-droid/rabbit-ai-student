const LANGUAGE_KEY = "study_buddy_language";

export function getSavedLanguage(): SupportedLanguage {
  try {
    const saved = localStorage.getItem(LANGUAGE_KEY);
    if (saved && SUPPORTED_LANGUAGES.some((l) => l.code === saved)) {
      return saved as SupportedLanguage;
    }
  } catch {
    // ignore
  }
  return "sr"; // Default to Serbian as requested by user
}

export function setSavedLanguage(lang: SupportedLanguage): void {
  try {
    localStorage.setItem(LANGUAGE_KEY, lang);
    window.dispatchEvent(new CustomEvent("study-buddy-lang-change", { detail: lang }));
  } catch {
    // ignore
  }
}

